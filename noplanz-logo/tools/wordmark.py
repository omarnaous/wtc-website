"""Builds src/brand.js: the No Planz wordmark as SVG outlines (Unbounded 800, OFL) with the final "z" replaced by
the mark, a Z drawn as one connection between two dots (two people), so the symbol and the word share one geometry.
  python3 tools/wordmark.py public/unbounded-latin-800-normal.woff2 src/brand.js"""
import sys, json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen

font = TTFont(sys.argv[1]); gs = font.getGlyphSet(); cmap = font.getBestCmap()
xh = font["OS/2"].sxHeight or 0
TRACK = -20                                    # tighten a little: big display setting
def glyph(ch):
    g = cmap[ord(ch)]; return g, gs[g]
def bounds(gn):
    bp = BoundsPen(gs); gs[gn].draw(bp); return bp.bounds
# stem: width of the "l" stem
lb = bounds(cmap[ord("l")]); stem = lb[2] - lb[0]
x, parts, letters = 0, [], []
for ch in "no plan":
    if ch == " ":
        x += font["hmtx"][cmap[ord(" ")]][0] * 0.62 + TRACK; continue
    gn, g = glyph(ch)
    pen = SVGPathPen(gs); tp = TransformPen(pen, (1, 0, 0, -1, x, 0)); g.draw(tp)
    letters.append({"ch": ch, "x": x, "w": g.width, "d": pen.getCommands()})
    x += g.width + TRACK
# the z: a Z the width of the "n" bowl, from a dot at top-left, along the top, down the diagonal, to a dot at bottom-right
nb = bounds(cmap[ord("n")]); zw = (nb[2] - nb[0]) * 0.8
sb = font["hmtx"][cmap[ord("n")]][1]
r, sw = stem * 0.56, stem * 0.74               # the dot radius and the route's stroke (as drawn in Logo.jsx)
zx0 = x + r * 0.9; zx1 = zx0 + zw
z = {"x0": zx0, "x1": zx1, "top": -xh + sw / 2, "bot": -sw / 2, "stem": stem, "sw": sw, "r": r}
total = zx1 + r
out = {"unitsPerEm": font["head"].unitsPerEm, "xHeight": xh, "stem": stem, "width": total, "letters": letters, "z": z}
open(sys.argv[2], "w").write("// generated by tools/wordmark.py: Unbounded 800 (SIL OFL) outlines in font units, baseline y = 0, up = negative\n"
  "export const WORD = " + json.dumps(out) + ";\n")
print("xHeight", xh, "stem", round(stem), "width", round(total), "letters", len(letters))
